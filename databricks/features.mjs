// Gathered: build workspace.gathered.person_features in Databricks, then prove parity with the
// local reference producer (lib/features/person-features.mjs) on the same V2 seed.
//
//   node databricks/features.mjs            build the Delta table and run the parity gate
//   node databricks/features.mjs --parity   parity gate only
//
// Writes databricks/PARITY_REPORT.md. Exits non-zero if parity is not 100%. The reference is never
// altered to make Databricks pass.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readCsv } from "../lib/seed/csv.mjs";
import { computePersonFeatures, FEATURE_COLUMNS } from "../lib/features/person-features.mjs";
import { NS, query, sql } from "./dbx.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const parityOnly = process.argv.includes("--parity");

if (!parityOnly) {
  const text = fs.readFileSync(path.join(HERE, "sql", "person_features.sql"), "utf8").replaceAll("{NS}", NS);
  await sql(text);
}

// ---- Databricks output
const dbx = await query(`select * from ${NS}.person_features`);
const describeAll = await query(`describe table ${NS}.person_features`);
const describe = describeAll.slice(0, describeAll.findIndex((d) => d.col_name.startsWith("#")) >>> 0 || undefined);
const ARRAYS = new Set(["signal_sources", "busy_slots", "serving_areas", "kids_age_bands"]);
const INTS = new Set(["observed_weeks_12w", "tenure_months"]);
const NUMS = new Set(["attendance_rate_12w", "online_share_12w", "consistency_score"]);
const norm = (col, v) => {
  if (v == null) return null;
  if (ARRAYS.has(col)) return JSON.parse(v);
  if (INTS.has(col)) return Number(v);
  if (NUMS.has(col)) return Number(v);
  return v;
};
const dbxById = new Map(dbx.map((r) => [r.person_id, r]));

// ---- local reference
const { asOf, rows: ref } = computePersonFeatures({
  people: readCsv("person.csv"), servingAssignments: readCsv("serving_assignment.csv"),
  ministries: readCsv("ministry.csv"), services: readCsv("service.csv"), attendance: readCsv("attendance_event.csv"),
});

// ---- compare
const result = { rows_ref: ref.size, rows_dbx: dbx.length, missing_in_dbx: 0, extra_in_dbx: 0, mismatches: {}, examples: [] };
for (const id of ref.keys()) if (!dbxById.has(id)) result.missing_in_dbx++;
for (const id of dbxById.keys()) if (!ref.has(id)) result.extra_in_dbx++;
const schemaCols = describe.map((d) => d.col_name);
const schemaOk = JSON.stringify(schemaCols) === JSON.stringify([...FEATURE_COLUMNS, "computed_at"]);
const cmpValue = (col, a, b) => {
  if (a == null || b == null) return a == null && b == null;
  if (NUMS.has(col)) return Math.abs(a - b) < 1e-9;
  if (ARRAYS.has(col)) return JSON.stringify(a) === JSON.stringify(b);
  return a === b;
};
let compared = 0, cellsOk = 0;
const nullCounts = {};
for (const [id, r] of ref) {
  const d = dbxById.get(id);
  if (!d) continue;
  for (const col of FEATURE_COLUMNS) {
    if (col === "person_id") continue;
    compared++;
    const a = r[col], b = norm(col, d[col]);
    if (b == null) nullCounts[col] = (nullCounts[col] ?? 0) + 1;
    if (cmpValue(col, a, b)) cellsOk++;
    else {
      result.mismatches[col] = (result.mismatches[col] ?? 0) + 1;
      if (result.examples.length < 8) result.examples.push({ person_id: id, col, reference: a, databricks: b });
    }
  }
}
const mismatchTotal = Object.values(result.mismatches).reduce((a, b) => a + b, 0);
const pass = result.rows_ref === result.rows_dbx && !result.missing_in_dbx && !result.extra_in_dbx && schemaOk && mismatchTotal === 0;

const types = Object.fromEntries(describe.map((d) => [d.col_name, d.data_type]));
const md = `# person_features parity report (Databricks vs local reference)

Generated by \`node databricks/features.mjs\`. Source: V2 seed (\`seed/out\`) loaded to \`${NS}\`. As-of date (latest service): ${asOf}.

**Result: ${pass ? "PASS: 100% parity" : "FAIL"}**

| Check | Result |
|---|---|
| Adults in reference / in Databricks | ${result.rows_ref} / ${result.rows_dbx} |
| Adults missing from Databricks / extra in Databricks | ${result.missing_in_dbx} / ${result.extra_in_dbx} |
| Column names and order equal the contract (\`FEATURE_COLUMNS\` + \`computed_at\`) | ${schemaOk ? "yes" : "NO"} |
| Cells compared (adults × ${FEATURE_COLUMNS.length - 1} feature columns) | ${compared} |
| Cells equal | ${cellsOk} |
| Mismatching cells | ${mismatchTotal}${mismatchTotal ? " " + JSON.stringify(result.mismatches) : ""} |

**Normalisation used (all explicit):** array columns are sorted sets in both producers and compared element by element; numeric columns are rounded to 4 places in both and compared with an absolute tolerance of 1e-9 (the Delta columns are \`decimal(5,4)\`); dates compare as \`YYYY-MM-DD\`; nulls must be null in both. Nothing else is normalised.

**Delta column types:** ${FEATURE_COLUMNS.concat("computed_at").map((c) => `${c} ${types[c]}`).join(", ")}.

**Null counts in Databricks (nullability behaviour equals the reference, which is where it is null):** ${JSON.stringify(nullCounts)}.
${result.examples.length ? "\n**First mismatches:**\n```\n" + JSON.stringify(result.examples, null, 1) + "\n```\n" : ""}`;
fs.writeFileSync(path.join(HERE, "PARITY_REPORT.md"), md);
console.log(md.split("\n").slice(0, 16).join("\n"));
process.exit(pass ? 0 : 1);
